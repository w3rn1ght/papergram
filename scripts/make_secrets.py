#!/usr/bin/env python3
"""Writes app/PGSecrets.h from CI secrets.

If the secrets are not configured (forks, pull requests, local builds), the
committed defaults are kept and the app asks for credentials on first launch.
"""

import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / "app" / "PGSecrets.h"

api_id = os.environ.get("TG_API_ID", "").strip()
api_hash = os.environ.get("TG_API_HASH", "").strip()

if not api_id.isdigit() or not api_hash:
    print("No API credentials in the environment; keeping the empty defaults.")
    sys.exit(0)

if len(api_hash) < 16:
    print("TG_API_HASH looks invalid; keeping the empty defaults.")
    sys.exit(0)

TARGET.write_text(
    "// Generated by scripts/make_secrets.py during CI. Do not commit.\n"
    "#ifndef PGSecrets_h\n"
    "#define PGSecrets_h\n"
    f"#define PG_BUILD_API_ID {api_id}\n"
    f'#define PG_BUILD_API_HASH @"{api_hash}"\n'
    "#endif\n",
    encoding="utf-8",
)

print("Wrote build-time API credentials to", TARGET.relative_to(ROOT))
